import type { AiProviderCode } from '../../packages/shared/src/index.ts';
import type { ModelSummary, Recommendation } from './analyse.ts';

export type ReportInput = {
  provider: AiProviderCode;
  experimentDate: string;
  passageCount: number;
  judgeLabel: string;
  appSetting: { model: string; setting: string };
  summaries: ModelSummary[];
  recommendation: Recommendation;
  notes: string[];
};

const PROVIDER_TITLES: Record<AiProviderCode, string> = {
  claude: 'Claude models',
  gemini: 'Gemini models',
};

function formatSeconds(milliseconds: number): string {
  return `${(milliseconds / 1000).toFixed(1)} s`;
}

function formatRange({
  minimum,
  maximum,
  format,
}: {
  minimum: number;
  maximum: number;
  format: (value: number) => string;
}): string {
  return `${format(minimum)}–${format(maximum)}`;
}

function formatCount(value: number): string {
  return Math.round(value).toLocaleString('en-US');
}

function formatDollars(value: number): string {
  return `$${value.toFixed(4)}`;
}

function formatPrice(value: number): string {
  return `$${value.toFixed(2)}`;
}

function decisionSentence({
  recommendation,
  appSetting,
}: {
  recommendation: Recommendation;
  appSetting: { model: string; setting: string };
}): string[] {
  const { recommended } = recommendation;
  if (!recommended) {
    return [recommendation.reason];
  }
  const matchesApp =
    recommended.model === appSetting.model && recommended.setting === appSetting.setting;
  const appLine = matchesApp
    ? `The app already uses this model at this setting.`
    : `The app uses \`${appSetting.model}\` at ${appSetting.setting}, so the app does not match this recommendation yet.`;
  return [
    `**Recommended for Explain: ${recommended.label}** (\`${recommended.model}\`, ${recommended.setting}).`,
    '',
    recommendation.reason,
    '',
    appLine,
  ];
}

function renderModelsSetup(summaries: ModelSummary[]): string[] {
  return [
    '| Model | ID | Effort or thinking level |',
    '|---|---|---|',
    ...summaries.map(
      (summary) => `| ${summary.label} | \`${summary.model}\` | ${summary.setting} |`,
    ),
  ];
}

function renderResults(summaries: ModelSummary[]): string[] {
  return [
    '| Model | Mean score (of 10) | Score range | Mean latency | Latency range | Mean input tokens | Mean output tokens | Mean thinking tokens | Wrong speaker or scene | Failed calls |',
    '|---|---|---|---|---|---|---|---|---|---|',
    ...summaries.map(
      (summary) =>
        `| ${summary.label} | ${summary.meanScore.toFixed(1)} | ${formatRange({ minimum: summary.minScore, maximum: summary.maxScore, format: (value) => String(value) })} | ${formatSeconds(summary.meanLatencyMs)} | ${formatRange({ minimum: summary.minLatencyMs, maximum: summary.maxLatencyMs, format: formatSeconds })} | ${formatCount(summary.meanInputTokens)} | ${formatCount(summary.meanOutputTokens)} | ${formatCount(summary.meanThinkingTokens)} | ${summary.wrongSpeakerOrScene} | ${summary.failedCalls} |`,
    ),
  ];
}

function renderCost(summaries: ModelSummary[]): string[] {
  const lines = [
    'Standard paid tier, USD per 1M tokens. Thinking tokens are billed at the output rate.',
    '',
    '| Model | Input | Output | Estimated cost per explanation | Upcoming cost per explanation |',
    '|---|---|---|---|---|',
  ];
  for (const summary of summaries) {
    const upcomingPrice = summary.price.from
      ? ` (from ${summary.price.from.date}: ${formatPrice(summary.price.from.inputPerMillion)})`
      : '';
    const upcomingOutput = summary.price.from
      ? ` (from ${summary.price.from.date}: ${formatPrice(summary.price.from.outputPerMillion)})`
      : '';
    const upcomingCost =
      summary.upcomingCostPerExplanation === null
        ? '—'
        : formatDollars(summary.upcomingCostPerExplanation);
    lines.push(
      `| ${summary.label} | ${formatPrice(summary.price.inputPerMillion)}${upcomingPrice} | ${formatPrice(summary.price.outputPerMillion)}${upcomingOutput} | ${formatDollars(summary.costPerExplanation)} | ${upcomingCost} |`,
    );
  }
  lines.push(
    '',
    'Estimates use the mean token counts above: input tokens × input price, plus (output + thinking tokens) × output price. They are not billing data.',
  );
  return lines;
}

export function renderReport(input: ReportInput): string {
  const sections = [
    `# ${PROVIDER_TITLES[input.provider]}: decision record`,
    '',
    '<!-- Generated by scripts/model-experiment. Edit the notes in scripts/model-experiment/candidates.ts instead. -->',
    '',
    '## Decision',
    '',
    ...decisionSentence({ recommendation: input.recommendation, appSetting: input.appSetting }),
    '',
    '## Models setup',
    '',
    ...renderModelsSetup(input.summaries),
    '',
    '## Experiment',
    '',
    `- **Date:** ${input.experimentDate}`,
    `- **Passages:** ${input.passageCount} passages from *Anna Karenina*, with fact keys (speaker, listener, scene, notable words), in \`scripts/model-experiment/passages.ts\`.`,
    `- **Settings:** the Explain prompt, a 4,000-token output cap, and the effort or thinking level above, from \`apps/server/src/lib/explain-settings.ts\`. Answers are in English.`,
    `- **Method:** one call per model per passage. The judge (${input.judgeLabel}) scores the answers blind: the answers are shuffled and labelled with letters, and the judge never sees which model wrote each one.`,
    '- **Criteria:** correct speaker and scene, correct meaning of unusual words, and no spoilers.',
    '',
    '## Results',
    '',
    ...renderResults(input.summaries),
    '',
    'Scores are from the judge against the fact keys. A failed call counts as 0. Latency is the total time of one call.',
    '',
    '## Cost',
    '',
    ...renderCost(input.summaries),
    '',
    '## Notes',
    '',
    ...input.notes.map((note) => `- ${note}`),
    '',
  ];
  return sections.join('\n');
}
